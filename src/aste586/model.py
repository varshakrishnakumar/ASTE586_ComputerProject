"""Shared, provided primitives: the state-vector layout and the ``Params``
object passed to the dynamics backend.

Both the student backend (``aste586.dynamics``) and the hidden reference
(``aste586_reference``) import from this module, so the two cannot drift apart
on conventions. Students do not edit this file.
"""

from __future__ import annotations

from dataclasses import dataclass, field

import numpy as np

# --- State-vector layout (see docs/conventions.md) -------------------------
#
#   rigid : z = [ w1 w2 w3  x y z w ]                          length 7
#   damped: z = [ w1 w2 w3  x y z w  Theta_d Omega_d ]          length 9
#
IDX_W = slice(0, 3)          # angular velocity, body coords (rad/s)
IDX_Q = slice(3, 7)          # attitude quaternion [x, y, z, w]
IDX_THETA_D = 7              # damper-wheel angle (rad)        -- damped only
IDX_OMEGA_D = 8              # damper-wheel rate  (rad/s)      -- damped only

STATE_LEN = {"rigid": 7, "damped": 9}


@dataclass
class Params:
    """Physical parameters handed to ``state_derivative``.

    Attributes
    ----------
    J : (3, 3) ndarray
        Principal inertia matrix, ``diag(I1, I2, I3)`` in kg-m^2.
    model : {"rigid", "damped"}
        Selects the equations of motion (Parts 2-3 vs. Part 4).
    torque : (3,) ndarray
        External torque in body coordinates. Zero for this project, but kept
        explicit so Euler's equations read naturally.
    Id, D, K : float
        Damper wheel inertia (kg-m^2), damping coefficient (N-m/(rad/s)) and
        spring coefficient (N-m/rad). Used only when ``model == "damped"``.
    """

    J: np.ndarray
    model: str = "rigid"
    torque: np.ndarray = field(default_factory=lambda: np.zeros(3))
    Id: float = 0.0
    D: float = 0.0
    K: float = 0.0

    @property
    def inertia(self) -> tuple[float, float, float]:
        """Principal moments ``(I1, I2, I3)`` as a convenience tuple."""
        return float(self.J[0, 0]), float(self.J[1, 1]), float(self.J[2, 2])
